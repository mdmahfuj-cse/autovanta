function buildImages(slug, primaryCat, secondaryCat, condition) {
  if (GALLERY_OVERRIDES[slug]) return GALLERY_OVERRIDES[slug];
  const pool = EXT_POOL[primaryCat] ?? EXT_POOL.sedan;
  const alt = (secondaryCat && EXT_POOL[secondaryCat]?.[0]) || pool[1] || pool[0];
  const interior =
    primaryCat === 'luxury' || (secondaryCat ?? '') === 'luxury' ? intTan : condition === 'New' ? intDark : intTan;
  return [pool[0], alt, interior, detailWheel];
}

function expandWarranty(code, condition) {
  if (condition === 'Certified Pre-Owned') return '12 mo AutoVanta CPO warranty';
  const [y, km] = code.split('/');
  return `${Number(y)} yr / ${Number(km).toLocaleString('en-US')} km manufacturer warranty`;
}

