const PREMIUM_CATS = new Set(['luxury', 'sports']);

export const CARS = RAW_CARS.map((r) => {
  const [layout, disp, cyl, asp, hp, tq, redline] = r.eng;
  const [accel, top, brake] = r.perf;
  const [lengthMm, widthMm, heightMm, wheelbaseMm, groundClearanceMm, bootLitres] = r.dims;
  const isEv = r.fuel === 'EV';
  const premium = r.cat.some((c) => PREMIUM_CATS.has(c));

  return {
    id: r.slug,
    slug: r.slug,
    brandId: r.brand,
    model: r.model,
    trim: r.trim,
    year: r.year,
    price: r.price,
    condition: r.condition,
    mileageKm: r.mileage,
    categories: r.cat,
    primaryCategory: r.cat[0],
    bodyType: r.body,
    fuel: r.fuel,
    transmission: r.trans,
    drivetrain: r.drive,
    engine: {
      layout,
      displacementL: disp || null,
      cylinders: cyl || null,
      aspiration: asp,
      powerHp: hp,
      powerKw: Math.round(hp * HP_TO_KW),
      torqueNm: tq,
      redlineRpm: redline,
    },
    performance: { zeroTo100: accel, topSpeedKmh: top, braking100to0m: brake },
    efficiency: isEv
      ? { combinedKmPerKwh: r.eff.kmPerKwh, rangeKm: r.eff.rangeKm }
      : { combinedKmpl: r.eff },
    seats: r.seats,
    warranty: expandWarranty(r.warranty, r.condition),
    dimensions: { lengthMm, widthMm, heightMm, wheelbaseMm, groundClearanceMm, bootLitres },
    safety: {
      rating: premium ? '5★ ASEAN NCAP (tested platform)' : '5★ ASEAN NCAP',
      features: [...DEFAULT_SAFETY, ...(premium ? ASSIST_KIT_PREMIUM : ASSIST_KIT_CORE)],
    },
    features: {
      comfort: premium ? [...COMFORT_KIT_PREMIUM, ...COMFORT_KIT.slice(0, 2)] : COMFORT_KIT,
      technology: premium ? TECH_KIT_PREMIUM : TECH_KIT,
      driverAssist: premium ? ASSIST_KIT_PREMIUM : ASSIST_KIT_CORE,
    },
    colors: r.colors.map((key) => ({ key, ...PAINT_PALETTE[key] })),
    images: buildImages(r.slug, r.cat[0], r.cat[1], r.condition).map((src, i) => ({
      src,
      kind: ['studio', 'exterior', 'interior', 'detail'][i] ?? 'detail',
      alt: `${r.brand} ${r.model} ${r.trim} — ${['studio shot', 'exterior angle', 'interior', 'detail'][i]}`,
    })),
    availability: r.avail,
    flags: r.flags ?? [],
    description: r.desc,
    highlights: r.highlights,
  };
});

