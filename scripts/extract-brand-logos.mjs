#!/usr/bin/env node
/**
 * Extracts brand logo vector paths into src/assets/brandLogos.js.
 *
 * Sources:
 *  - 9 marques from the `simple-icons` package (CC0-licensed path data).
 *  - Mercedes + Jaguar from scripts/vendor/simple-icons-legacy/ (archived
 *    simple-icons 9.21.0 files — removed from newer releases at the
 *    brands' request, still CC0).
 *  - Lexus never existed in simple-icons — hand-drawn stroke mark
 *    (oval + L-sweep) in the same 24x24 grid.
 *
 * Brand names and logos are trademarks of their respective owners;
 * used nominatively in this demo showroom. Re-run: node scripts/extract-brand-logos.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as si from 'simple-icons';

const root = fileURLToPath(new URL('../', import.meta.url));

/** @type {Record<string, string>} brand id -> simple-icons export key */
const SI_KEYS = {
  toyota: 'siToyota',
  honda: 'siHonda',
  bmw: 'siBmw',
  audi: 'siAudi',
  porsche: 'siPorsche',
  tesla: 'siTesla',
  hyundai: 'siHyundai',
  ford: 'siFord',
  mazda: 'siMazda',
};

function pathFromLegacySvg(file) {
  const svg = readFileSync(new URL(`./vendor/simple-icons-legacy/${file}`, import.meta.url), 'utf8');
  const d = / d="([^"]+)"/.exec(svg)?.[1];
  if (!d) throw new Error(`no path d found in ${file}`);
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`unexpected viewBox in ${file}`);
  return d;
}

/** @type {Record<string, object>} */
const logos = {};
for (const [id, key] of Object.entries(SI_KEYS)) {
  const icon = si[key];
  if (!icon) throw new Error(`simple-icons export ${key} missing — pin the package version`);
  logos[id] = { d: icon.path };
}
logos.mercedes = { d: pathFromLegacySvg('mercedes.svg') };
logos.jaguar = { d: pathFromLegacySvg('jaguar.svg') };
// Hand-drawn Lexus mark: enclosing oval (the "L" foot) + sweeping diagonal stroke.
logos.lexus = {
  strokeWidth: 1.4,
  stroke: [
    { tag: 'ellipse', props: { cx: 12, cy: 12, rx: 10.4, ry: 7.1 } },
    { tag: 'path', props: { d: 'M13.9 5.5Q9.7 11.8 4.9 16.6' } },
  ],
};

for (const [id, logo] of Object.entries(logos)) {
  if (logo.d && logo.d.length < 40) throw new Error(`${id}: path suspiciously short`);
}

const banner = `/**
 * AUTO-GENERATED by scripts/extract-brand-logos.mjs — do not edit by hand.
 * 24x24 monochrome brand marks: { d } = fill path, { stroke, strokeWidth } = stroked shapes.
 * Logos are trademarks of their respective owners (see script header for sources).
 */

/**
 * @type {Record<string, { d?: string, stroke?: Array<{ tag: string, props: Record<string, string|number> }>, strokeWidth?: number }>}
 */
export const BRAND_LOGOS = ${JSON.stringify(logos, null, 2)};
`;

writeFileSync(new URL('../src/assets/brandLogos.js', import.meta.url), banner);
const sizes = Object.entries(logos).map(([id, l]) => `${id}:${(l.d ?? JSON.stringify(l.stroke)).length}b`);
console.log('Wrote src/assets/brandLogos.js —', sizes.join(', '));
